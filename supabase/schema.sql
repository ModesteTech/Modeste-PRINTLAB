-- Modeste PRINTLAB : table des avis et règles d'accès.
-- À exécuter une seule fois dans Supabase > SQL Editor > New query.
-- Les visiteurs peuvent lire les avis publiés et soumettre des avis en attente.
-- Les visiteurs ne peuvent pas publier, modifier ou supprimer des avis eux-mêmes.

create table if not exists public.avis (
    id bigint generated by default as identity primary key,
    nom text not null check (char_length(trim(nom)) between 1 and 40),
    ecole text check (ecole is null or char_length(ecole) <= 60),
    note integer not null check (note between 1 and 5),
    commentaire text not null check (char_length(trim(commentaire)) between 1 and 600),
    statut text not null default 'pending' check (statut in ('pending', 'published', 'rejected')),
    created_at timestamptz not null default now()
);

alter table public.avis enable row level security;

-- Retirer les droits par défaut puis redonner seulement ce dont le site a besoin.
revoke all on table public.avis from anon, authenticated;
grant select, insert on table public.avis to anon;
grant select, insert on table public.avis to authenticated;

-- Les visiteurs ne peuvent lire que les avis publiés.
drop policy if exists "Tout le monde lit les avis publiés" on public.avis;
create policy "Tout le monde lit les avis publiés"
on public.avis
for select
to anon, authenticated
using (statut = 'published');

-- Les visiteurs peuvent soumettre un avis en attente, jamais le publier directement.
drop policy if exists "Les visiteurs soumettent un avis en attente" on public.avis;
create policy "Les visiteurs soumettent un avis en attente"
on public.avis
for insert
to anon, authenticated
with check (statut = 'pending');

-- Important : aucune règle UPDATE ou DELETE n'est créée pour les visiteurs.
-- Pour valider un avis, connecte-toi au tableau de bord Supabase et change
-- son statut de 'pending' à 'published'. Pour le refuser, utilise 'rejected'.
-- Effectue cette validation depuis le tableau de bord, jamais avec une clé secrète dans le site.
